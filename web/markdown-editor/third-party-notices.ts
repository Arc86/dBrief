import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import type { Plugin } from "vite";

// Emits THIRD-PARTY-NOTICES.txt beside editor.js: name, version, license and the
// full license text of every npm package whose code ends up in the bundle. The
// minified bundle drops license comments, and MIT/BSD require the notice to ship.
export function thirdPartyNotices(): Plugin {
  return {
    name: "dbrief-third-party-notices",
    apply: "build",
    generateBundle() {
      const packageDirs = new Set<string>();
      for (const id of this.getModuleIds()) {
        const dir = packageDir(id);
        if (dir) packageDirs.add(dir);
      }
      const entries = [...packageDirs]
        .map((dir) => {
          const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
          return { name: pkg.name as string, version: pkg.version as string, license: licenseOf(pkg), text: licenseText(dir) };
        })
        .sort((a, b) => a.name.localeCompare(b.name));
      const header =
        "The summary editor (editor.js, editor.css) bundles the following open-source packages.\n" +
        "This file is generated by `npm run build` in web/markdown-editor.\n";
      const body = entries
        .map((e) => `${"=".repeat(72)}\n${e.name} ${e.version} (${e.license})\n${"=".repeat(72)}\n\n${e.text ?? "No license file in the package; see its package.json license field."}\n`)
        .join("\n");
      this.emitFile({ type: "asset", fileName: "THIRD-PARTY-NOTICES.txt", source: `${header}\n${body}` });
    },
  };
}

/** The package root for a module id inside node_modules, or undefined for our own sources. */
function packageDir(id: string): string | undefined {
  const path = id.replace(/^\0/, "").split("?")[0];
  const marker = "/node_modules/";
  const at = path.lastIndexOf(marker);
  if (at < 0) return undefined;
  const rest = path.slice(at + marker.length).split("/");
  const segments = rest[0].startsWith("@") ? 2 : 1;
  const dir = path.slice(0, at + marker.length) + rest.slice(0, segments).join("/");
  return existsSync(join(dir, "package.json")) ? dir : undefined;
}

function licenseOf(pkg: { license?: unknown; licenses?: unknown }): string {
  if (typeof pkg.license === "string") return pkg.license;
  if (pkg.license && typeof pkg.license === "object" && "type" in pkg.license) return String(pkg.license.type);
  return "UNKNOWN";
}

function licenseText(dir: string): string | undefined {
  const file = readdirSync(dir).find((name) => /^(licen[cs]e|copying)(\.|$)/i.test(name));
  return file ? readFileSync(join(dir, file), "utf8").trim() : undefined;
}
